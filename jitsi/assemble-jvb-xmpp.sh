#!/bin/bash
# Assemble videobridge.apis.xmpp-client.configs from per-customer drop-in files.
# Official docker-jitsi-meet only accepts a comma-separated XMPP_SERVER list that
# shares one domain and one password. JVB itself supports different hostname,
# domain, password and brewery MUC per connection (see jitsi-videobridge doc/muc.md
# and the include "custom-jvb.conf" hook in the official jvb.conf template).
#
# Safe to run on the host (install.sh / purge.sh) or inside the JVB container
# (jvb-entrypoint.sh). Does not print secret values.
set -euo pipefail

CONFIG_DIR="${JITSI_JVB_CONFIG_DIR:-/config}"
DROPIN_DIR="${JITSI_XMPP_SERVERS_DIR:-/xmpp-servers}"
OUT="${CONFIG_DIR}/custom-jvb.conf"

mkdir -p "$CONFIG_DIR"

tmp="${OUT}.tmp.$$"
{
    echo '// Generated by assemble-jvb-xmpp.sh — do not edit this file.'
    echo '// Add or remove drop-ins under the xmpp-servers directory instead.'
    echo 'videobridge {'
    echo '  apis {'
    echo '    xmpp-client {'
    echo '      configs {'
    if [ -d "$DROPIN_DIR" ]; then
        shopt -s nullglob
        for f in "$DROPIN_DIR"/*.conf; do
            echo "        // from $(basename "$f")"
            sed 's/^/        /' "$f"
            echo
        done
        shopt -u nullglob
    fi
    echo '      }'
    echo '    }'
    echo '  }'
    echo '}'
} > "$tmp"
chmod 600 "$tmp"
mv "$tmp" "$OUT"
