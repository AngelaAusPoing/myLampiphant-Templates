#!/bin/bash
# linuxserver custom-cont-init: apply DOKUWIKI_AUTH / DOKUWIKI_ACCESS.
# Runs as root at every container start. Never prints secrets.
# Touches only local.protected.php, plugins.local.php (authldap flag) and
# the catch-all ACL lines when access is closed. Leaves local.php and
# users.auth.php alone.
set -euo pipefail

CONF="${DOKUWIKI_CONF_DIR:-/config/dokuwiki/conf}"
AUTH="${DOKUWIKI_AUTH:-plain}"
ACCESS="${DOKUWIKI_ACCESS:-open}"
PUID="${PUID:-1000}"
PGID="${PGID:-1000}"

log() { echo "[dokuwiki-options] $*"; }

if [ ! -f "${CONF}/local.php" ]; then
    log "local.php not present yet (installer unfinished); skipping"
    exit 0
fi

# ---------------------------------------------------------------------------
# LDAP bind password: root copies the host-mounted secret to a php-readable
# path in /run (tmpfs). The value is not written into PHP sources.
# ---------------------------------------------------------------------------
BIND_PW_PHP="/run/secrets/ldap-bind.pw"
rm -f "$BIND_PW_PHP"
if [ "$AUTH" = "ldap" ]; then
    src=""
    if [ -s /run/secrets/ldap-readonly-host.pw ]; then
        src=/run/secrets/ldap-readonly-host.pw
    elif [ -s /run/secrets/ldap-bind.pw.host ]; then
        src=/run/secrets/ldap-bind.pw.host
    fi
    if [ -z "$src" ]; then
        log "ERROR: DOKUWIKI_AUTH=ldap but no bind secret is mounted at /run/secrets/ldap-readonly-host.pw"
        exit 1
    fi
    mkdir -p /run/secrets
    umask 077
    cp "$src" "$BIND_PW_PHP"
    chown "${PUID}:${PGID}" "$BIND_PW_PHP"
    chmod 640 "$BIND_PW_PHP"
fi

# ---------------------------------------------------------------------------
# local.protected.php (rewritten every start; not editable in the admin UI)
# Values are baked from the container environment here (PHP-FPM may not
# inherit Docker env). The bind password is still read from the secret file.
# ---------------------------------------------------------------------------
PROTECTED="${CONF}/local.protected.php"
admingrp="${LDAP_ADMIN_GROUP:-wiki-admin}"
case "$admingrp" in
    *'!!'*|"") admingrp=wiki-admin ;;
esac
server="${LDAP_SERVER:-ldap://ldap:389}"
binddn="${LDAP_BIND_DN:-cn=readonly,ou=system,dc=lampiphant,dc=de}"
usertree="${LDAP_USER_TREE:-}"
grouptree="${LDAP_GROUP_TREE:-}"

# Tokens of the form __NAME__ are replaced below. Values must not contain __ .
cat > "$PROTECTED" <<'PHP'
<?php
/**
 * Generated by myLampiphant apply-options.sh at container start.
 * Do not edit; this file is rewritten on every start.
 * Secrets are read from /run/secrets, never hardcoded here.
 */
PHP

if [ "$AUTH" = "ldap" ]; then
    cat >> "$PROTECTED" <<'PHP'
$conf['authtype'] = 'authldap';
$conf['superuser'] = '@__LDAP_ADMIN_GROUP__';
$conf['disableactions'] = 'register,resendpwd';
$conf['plugin']['authldap']['server']      = '__LDAP_SERVER__';
$conf['plugin']['authldap']['port']        = 389;
$conf['plugin']['authldap']['version']     = 3;
$conf['plugin']['authldap']['starttls']    = 0;
$conf['plugin']['authldap']['referrals']   = 0;
$conf['plugin']['authldap']['usertree']    = '__LDAP_USER_TREE__';
$conf['plugin']['authldap']['grouptree']   = '__LDAP_GROUP_TREE__';
$conf['plugin']['authldap']['userfilter']  = '(&(objectClass=inetOrgPerson)(uid=%{user}))';
$conf['plugin']['authldap']['groupfilter'] = '(&(objectClass=groupOfNames)(member=%{dn}))';
$conf['plugin']['authldap']['userkey']     = 'uid';
$conf['plugin']['authldap']['groupkey']    = 'cn';
$conf['plugin']['authldap']['userscope']   = 'sub';
$conf['plugin']['authldap']['groupscope']  = 'sub';
$conf['plugin']['authldap']['binddn']      = '__LDAP_BIND_DN__';
$bindpw_file = '/run/secrets/ldap-bind.pw';
$conf['plugin']['authldap']['bindpw']      = is_readable($bindpw_file) ? trim((string) file_get_contents($bindpw_file)) : '';
$conf['plugin']['authldap']['modPass']     = 0;
$conf['plugin']['authldap']['mapping']['name'] = 'cn';
$conf['plugin']['authldap']['mapping']['grps'] = array('memberOf' => '/cn=([^,]+)/i');
$conf['plugin']['authldap']['attributes'] = array('cn', 'givenName', 'sn', 'mail', 'uid', 'memberOf', 'displayname');
PHP
    awk -v admin="$admingrp" -v server="$server" -v binddn="$binddn" \
        -v usertree="$usertree" -v grouptree="$grouptree" '
        {
            gsub(/__LDAP_ADMIN_GROUP__/, admin)
            gsub(/__LDAP_SERVER__/, server)
            gsub(/__LDAP_BIND_DN__/, binddn)
            gsub(/__LDAP_USER_TREE__/, usertree)
            gsub(/__LDAP_GROUP_TREE__/, grouptree)
            print
        }
    ' "$PROTECTED" > "${PROTECTED}.tmp"
    mv "${PROTECTED}.tmp" "$PROTECTED"
elif [ "$ACCESS" = "closed" ]; then
    cat >> "$PROTECTED" <<'PHP'
$conf['disableactions'] = 'register';
PHP
fi

chown "${PUID}:${PGID}" "$PROTECTED"
chmod 640 "$PROTECTED"

# ---------------------------------------------------------------------------
# Enable bundled authldap when LDAP is selected (installer disables it).
# ---------------------------------------------------------------------------
PLUGINS="${CONF}/plugins.local.php"
if [ "$AUTH" = "ldap" ]; then
    if [ -f "$PLUGINS" ]; then
        if grep -q "\$plugins\['authldap'\]" "$PLUGINS"; then
            sed -i "s/\$plugins\['authldap'\]\s*=\s*0\s*;/\$plugins['authldap']  = 1;/" "$PLUGINS"
        else
            printf "\n\$plugins['authldap']  = 1;\n" >> "$PLUGINS"
        fi
    else
        printf "<?php\n\$plugins['authldap']  = 1;\n" > "$PLUGINS"
        chown "${PUID}:${PGID}" "$PLUGINS"
        chmod 644 "$PLUGINS"
    fi
fi

# ---------------------------------------------------------------------------
# Closed wiki: only logged-in users can read. Preserve any extra ACL rules.
# ---------------------------------------------------------------------------
ACL="${CONF}/acl.auth.php"
if [ "$ACCESS" = "closed" ]; then
    if [ ! -f "$ACL" ]; then
        cat > "$ACL" <<'ACL'
# acl.auth.php
# <?php exit()?>
# Don't modify the lines above
#
# Access Control Lists
#
*               @ALL          0
*               @user         8
ACL
        chown "${PUID}:${PGID}" "$ACL"
        chmod 644 "$ACL"
    else
        tmp="${ACL}.tmp"
        awk '
            /^\*[[:space:]]+@ALL[[:space:]]+[0-9]+[[:space:]]*$/ {
                sub(/[0-9]+[[:space:]]*$/, "0")
                saw_all=1
                print
                next
            }
            /^\*[[:space:]]+@user[[:space:]]+[0-9]+[[:space:]]*$/ {
                sub(/[0-9]+[[:space:]]*$/, "8")
                saw_user=1
                print
                next
            }
            { print }
            END {
                if (!saw_all) print "*               @ALL          0"
                if (!saw_user) print "*               @user         8"
            }
        ' "$ACL" > "$tmp"
        mv "$tmp" "$ACL"
        chown "${PUID}:${PGID}" "$ACL"
        chmod 644 "$ACL"
    fi
fi

log "applied auth=${AUTH} access=${ACCESS}"
